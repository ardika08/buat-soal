-- P0 Security Hotfix
--
-- Menutup tiga celah kritis hasil audit:
--   1. Pengguna terautentikasi dapat mengubah kredit/tier/expiry langsung dari Data API.
--   2. Checkout memberi benefit tanpa pembayaran terverifikasi (tanpa order, idempotensi, atau ledger).
--   3. Pengurangan kredit, penyimpanan ujian, dan ledger tidak atomik (race + partial write).
--
-- Prinsip: semua mutasi kredit hanya melalui fungsi security definer yang mengunci baris profil
-- (SELECT ... FOR UPDATE), menulis ledger, dan idempoten terhadap idempotency key.

-- ---------------------------------------------------------------------------
-- 1. Cabut akses UPDATE langsung ke kolom billing pada profil
-- ---------------------------------------------------------------------------

revoke update on public.profiles from authenticated;
revoke update on public.profiles from anon;
revoke insert, delete on public.profiles from authenticated;
revoke insert, delete on public.profiles from anon;

drop policy if exists "Users can update own profile" on public.profiles;

-- Satu-satunya jalur update profil untuk pengguna: ubah nama saja.
create or replace function public.update_own_profile(p_name text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_profile public.profiles;
begin
  if p_name is null or length(btrim(p_name)) < 2 then
    raise exception 'Nama minimal 2 karakter.' using errcode = '22023';
  end if;

  if length(btrim(p_name)) > 120 then
    raise exception 'Nama maksimal 120 karakter.' using errcode = '22023';
  end if;

  update public.profiles
     set name = btrim(p_name)
   where auth_user_id = auth.uid()
  returning * into v_profile;

  if v_profile.id is null then
    raise exception 'Profil tidak ditemukan.' using errcode = 'P0002';
  end if;

  return to_jsonb(v_profile);
end;
$$;

revoke all on function public.update_own_profile(text) from public;
revoke all on function public.update_own_profile(text) from anon;
grant execute on function public.update_own_profile(text) to authenticated;

