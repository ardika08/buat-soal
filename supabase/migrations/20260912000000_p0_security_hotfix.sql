  on public.exam_sessions (idempotency_key)
  where idempotency_key is not null;

-- ---------------------------------------------------------------------------
-- 3. Payment orders (sumber kebenaran pembayaran)
-- ---------------------------------------------------------------------------

create table if not exists public.payment_orders (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.profiles(id) on delete cascade,
  package_id text not null,
  order_type text not null check (order_type in ('topup', 'subscription')),
  provider text not null default 'mayar',
  provider_order_id text unique,
  provider_transaction_id text,
  status text not null default 'pending' check (status in ('pending', 'paid', 'expired', 'failed', 'cancelled')),
  amount integer not null check (amount >= 0),
  credits integer not null check (credits >= 0),
  duration_months integer,
  checkout_url text,
  customer_name text,
  customer_email text,
  customer_mobile text,
  paid_at timestamptz,
  fulfilled_at timestamptz,
  credits_granted integer,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists payment_orders_user_created_idx
  on public.payment_orders (user_id, created_at desc);

create index if not exists payment_orders_status_idx
  on public.payment_orders (status);

drop trigger if exists payment_orders_set_updated_at on public.payment_orders;
create trigger payment_orders_set_updated_at
before update on public.payment_orders
for each row execute function public.set_updated_at();

alter table public.payment_orders enable row level security;

revoke insert, update, delete on public.payment_orders from authenticated;
revoke insert, update, delete on public.payment_orders from anon;

-- RLS hanya menyaring baris; akses tabel tetap butuh GRANT eksplisit.
grant select on public.payment_orders to authenticated;
revoke select on public.payment_orders from anon;

drop policy if exists "Users can read own payment orders" on public.payment_orders;
create policy "Users can read own payment orders"
on public.payment_orders for select
to authenticated
using (user_id in (select id from public.profiles where auth_user_id = auth.uid()));

