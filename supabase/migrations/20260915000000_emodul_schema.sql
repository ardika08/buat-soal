-- E-Modul: sesi penyusunan, bab, dan bagian (subbab materi & latihan).
--
-- Satu e-modul (`e_modul_sessions`) berisi banyak bab (`e_modul_chapters`); tiap
-- bab berisi bagian di `e_modul_sections` dengan jenis 'materi' (subbab) atau
-- 'latihan'. Subbab dan latihan sengaja berbagi satu tabel agar nomor urut rapat
-- lintas jenis — sesuai urutan bagian yang disunting di editor.
--
-- Pola keamanan sama dengan bank soal: klien hanya boleh membaca miliknya; semua
-- mutasi lewat RPC SECURITY DEFINER yang dibuat pada task berikutnya.

create table if not exists public.e_modul_sessions (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.profiles(id) on delete cascade,
  title text not null default 'E-Modul Baru',
  topics jsonb not null default '[]'::jsonb,          -- [{ topik, capaian }]
  fase text not null default '',
  kelas text not null default '',
  subject text not null default '',
  semester text not null default 'Ganjil',
  chapters_target smallint not null default 4 check (chapters_target between 1 and 12),
  sub_chapters_target smallint not null default 2 check (sub_chapters_target between 1 and 6),
  exercise_share smallint not null default 30 check (exercise_share between 0 and 60),
  status text not null default 'draft' check (status in ('draft', 'ready')),
  credits_consumed integer not null default 0 check (credits_consumed >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists e_modul_sessions_user_created_idx
  on public.e_modul_sessions(user_id, created_at desc);

create table if not exists public.e_modul_chapters (
  id bigint generated by default as identity primary key,
  e_modul_id bigint not null references public.e_modul_sessions(id) on delete cascade,
  order_number integer not null check (order_number > 0),
  title text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (e_modul_id, order_number)
);

create index if not exists e_modul_chapters_modul_idx
  on public.e_modul_chapters(e_modul_id, order_number);

create table if not exists public.e_modul_sections (
  id bigint generated by default as identity primary key,
  chapter_id bigint not null references public.e_modul_chapters(id) on delete cascade,
  order_number integer not null check (order_number > 0),
  kind text not null check (kind in ('materi', 'latihan')),
  title text not null default '',
  content text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (chapter_id, order_number)
);

create index if not exists e_modul_sections_chapter_idx
  on public.e_modul_sections(chapter_id, order_number);

-- Timestamp updated_at otomatis (fungsi dari schema awal).
drop trigger if exists e_modul_sessions_set_updated_at on public.e_modul_sessions;
create trigger e_modul_sessions_set_updated_at
before update on public.e_modul_sessions
for each row execute function public.set_updated_at();

drop trigger if exists e_modul_chapters_set_updated_at on public.e_modul_chapters;
create trigger e_modul_chapters_set_updated_at
before update on public.e_modul_chapters
for each row execute function public.set_updated_at();

drop trigger if exists e_modul_sections_set_updated_at on public.e_modul_sections;
create trigger e_modul_sections_set_updated_at
before update on public.e_modul_sections
for each row execute function public.set_updated_at();

alter table public.e_modul_sessions enable row level security;
alter table public.e_modul_chapters enable row level security;
alter table public.e_modul_sections enable row level security;

drop policy if exists "Users can read own e-moduls" on public.e_modul_sessions;
create policy "Users can read own e-moduls"
on public.e_modul_sessions for select to authenticated
using (user_id in (select id from public.profiles where auth_user_id = auth.uid()));

drop policy if exists "Users can read own e-modul chapters" on public.e_modul_chapters;
create policy "Users can read own e-modul chapters"
on public.e_modul_chapters for select to authenticated
using (
  e_modul_id in (
    select m.id
    from public.e_modul_sessions m
    join public.profiles p on p.id = m.user_id
    where p.auth_user_id = auth.uid()
  )
);

drop policy if exists "Users can read own e-modul sections" on public.e_modul_sections;
create policy "Users can read own e-modul sections"
on public.e_modul_sections for select to authenticated
using (
  chapter_id in (
    select c.id
    from public.e_modul_chapters c
    join public.e_modul_sessions m on m.id = c.e_modul_id
    join public.profiles p on p.id = m.user_id
    where p.auth_user_id = auth.uid()
  )
);

-- Semua mutasi lewat RPC yang memverifikasi kepemilikan.
revoke insert, update, delete on public.e_modul_sessions from authenticated, anon;
revoke insert, update, delete on public.e_modul_chapters from authenticated, anon;
revoke insert, update, delete on public.e_modul_sections from authenticated, anon;

grant select on public.e_modul_sessions to authenticated;
grant select on public.e_modul_chapters to authenticated;
grant select on public.e_modul_sections to authenticated;

revoke select on public.e_modul_sessions from anon;
revoke select on public.e_modul_chapters from anon;
revoke select on public.e_modul_sections from anon;
