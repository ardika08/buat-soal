do $$ begin
  create type public.payment_order_status as enum ('pending', 'paid', 'expired', 'failed');
exception
  when duplicate_object then null;
end $$;
create table if not exists public.payment_orders (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.profiles(id) on delete cascade,
  package_id text not null,
  provider text not null default 'mayar',
  provider_payment_id text,
  provider_transaction_id text,
  customer_name text not null,
  customer_email text not null,
  customer_mobile text not null,
  amount integer not null check (amount >= 0),
  status public.payment_order_status not null default 'pending',
  checkout_url text,
  redirect_url text,
  package_snapshot jsonb not null,
  raw_create_response jsonb,
  raw_last_status jsonb,
  fulfilled_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (provider_transaction_id)
);

-- Existing databases may contain an earlier payment_orders table without all
-- provider columns; add these idempotently before creating indexes.
alter table public.payment_orders
  add column if not exists provider text not null default 'mayar',
  add column if not exists provider_payment_id text,
  add column if not exists provider_transaction_id text;

create index if not exists payment_orders_user_created_idx on public.payment_orders(user_id, created_at desc);
create index if not exists payment_orders_provider_payment_idx on public.payment_orders(provider_payment_id);
create index if not exists payment_orders_provider_tx_idx on public.payment_orders(provider_transaction_id);
drop trigger if exists payment_orders_set_updated_at on public.payment_orders;
create trigger payment_orders_set_updated_at
before update on public.payment_orders
for each row execute function public.set_updated_at();
alter table public.payment_orders enable row level security;
drop policy if exists "Users can read own payment orders" on public.payment_orders;
create policy "Users can read own payment orders"
on public.payment_orders for select
to authenticated
using (user_id in (select id from public.profiles where auth_user_id = auth.uid()));
create or replace function public.fulfill_payment_order(p_order_id bigint)
returns table (
  order_id bigint,
  user_id bigint,
  subscription_tier public.subscription_tier,
  credits_balance integer,
  subscription_expiry timestamptz,
  already_fulfilled boolean
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.payment_orders%rowtype;
  v_profile public.profiles%rowtype;
  v_package jsonb;
  v_credits integer;
  v_duration_months integer;
  v_subscription_tier public.subscription_tier;
  v_subscription_expiry timestamptz;
  v_tx_type public.credit_transaction_type;
  v_description text;
begin
  select * into v_order
  from public.payment_orders
  where id = p_order_id
  for update;

  if not found then
    raise exception 'Payment order % not found', p_order_id;
  end if;

  select * into v_profile
  from public.profiles
  where id = v_order.user_id
  for update;

  if not found then
    raise exception 'Profile for payment order % not found', p_order_id;
  end if;

  if v_order.fulfilled_at is not null then
    return query
    select
      v_order.id,
      v_profile.id,
      v_profile.subscription_tier,
      v_profile.credits_balance,
      v_profile.subscription_expiry,
      true;
    return;
  end if;

  v_package := v_order.package_snapshot;
  v_credits := coalesce((v_package->>'credits')::integer, 0);
  v_duration_months := nullif(v_package->>'duration_months', '')::integer;
  v_subscription_tier := v_profile.subscription_tier;
  v_subscription_expiry := v_profile.subscription_expiry;
  v_tx_type := case
    when coalesce(v_package->>'type', '') = 'subscription' then 'subscription'::public.credit_transaction_type
    else 'topup'::public.credit_transaction_type
  end;
  v_description := coalesce(v_package->>'name', 'Pembayaran paket')
    || ' - Rp '
    || coalesce(v_package->>'price', '0');

  if coalesce(v_package->>'type', '') = 'subscription' then
    v_subscription_tier := 'premium';
    v_subscription_expiry := (
      case
        when v_profile.subscription_expiry is not null and v_profile.subscription_expiry > now()
          then v_profile.subscription_expiry
        else now()
      end
    ) + make_interval(months => coalesce(v_duration_months, 0));
  end if;

  update public.profiles
  set credits_balance = credits_balance + v_credits,
      subscription_tier = v_subscription_tier,
      subscription_expiry = v_subscription_expiry,
      updated_at = now()
  where id = v_profile.id
  returning * into v_profile;

  insert into public.credit_transactions (user_id, type, amount, description)
  values (v_profile.id, v_tx_type, v_credits, v_description);

  update public.payment_orders
  set status = 'paid',
      fulfilled_at = now(),
      updated_at = now()
  where id = v_order.id
  returning * into v_order;

  return query
  select
    v_order.id,
    v_profile.id,
    v_profile.subscription_tier,
    v_profile.credits_balance,
    v_profile.subscription_expiry,
    false;
end;
$$;
