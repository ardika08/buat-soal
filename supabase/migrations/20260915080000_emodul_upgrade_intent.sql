-- Niat upgrade E-Book yang tertunda (server).
--
-- Disimpan saat pengguna gratis menekan unduhan terkunci. Setelah upgrade,
-- aplikasi mengambil niat ini (status `pending`) lalu menandainya `resumed`
-- untuk melanjutkan alur di halaman asal. Hanya satu niat pending per pengguna.

create table if not exists public.emodul_upgrade_intents (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.profiles(id) on delete cascade,
  return_to text not null,
  action text not null check (action in ('download_pdf', 'download_docx')),
  status text not null default 'pending' check (status in ('pending', 'resumed', 'cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists emodul_upgrade_intents_user_status_idx
  on public.emodul_upgrade_intents(user_id, status, created_at desc);

alter table public.emodul_upgrade_intents enable row level security;

drop policy if exists "Users can read own emodul upgrade intents" on public.emodul_upgrade_intents;
create policy "Users can read own emodul upgrade intents"
on public.emodul_upgrade_intents for select to authenticated
using (user_id in (select id from public.profiles where auth_user_id = auth.uid()));

revoke insert, update, delete on public.emodul_upgrade_intents from authenticated, anon;
grant select on public.emodul_upgrade_intents to authenticated;
revoke select on public.emodul_upgrade_intents from anon;

drop trigger if exists emodul_upgrade_intents_set_updated_at on public.emodul_upgrade_intents;
create trigger emodul_upgrade_intents_set_updated_at
before update on public.emodul_upgrade_intents
for each row execute function public.set_updated_at();

create or replace function public.save_emodul_upgrade_intent(
  p_user_id bigint,
  p_return_to text,
  p_action text
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_intent jsonb;
begin
  if p_action not in ('download_pdf', 'download_docx') then
    raise exception 'invalid_action';
  end if;

  if p_return_to is null
     or p_return_to not like '/%'
     or p_return_to like '//%'
     or length(p_return_to) > 500 then
    raise exception 'invalid_return_to';
  end if;

  -- Hanya satu niat pending: batalkan yang lama agar tidak menumpuk.
  update public.emodul_upgrade_intents
  set status = 'cancelled'
  where user_id = p_user_id and status = 'pending';

  insert into public.emodul_upgrade_intents (user_id, return_to, action)
  values (p_user_id, p_return_to, p_action)
  returning to_jsonb(emodul_upgrade_intents) into v_intent;

  return v_intent;
end;
$$;

create or replace function public.get_emodul_upgrade_intent(p_user_id bigint)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select to_jsonb(i.*)
  from public.emodul_upgrade_intents i
  where i.user_id = p_user_id and i.status = 'pending'
  order by i.created_at desc
  limit 1;
$$;

create or replace function public.resume_emodul_upgrade_intent(p_user_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_intent jsonb;
begin
  update public.emodul_upgrade_intents
  set status = 'resumed'
  where id = (
    select id
    from public.emodul_upgrade_intents
    where user_id = p_user_id and status = 'pending'
    order by created_at desc
    limit 1
  )
  returning to_jsonb(emodul_upgrade_intents) into v_intent;

  return v_intent;
end;
$$;

create or replace function public.cancel_emodul_upgrade_intent(p_user_id bigint)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_count integer;
begin
  update public.emodul_upgrade_intents
  set status = 'cancelled'
  where user_id = p_user_id and status = 'pending';

  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

revoke all on function public.save_emodul_upgrade_intent(bigint, text, text) from public, anon, authenticated;
revoke all on function public.get_emodul_upgrade_intent(bigint) from public, anon, authenticated;
revoke all on function public.resume_emodul_upgrade_intent(bigint) from public, anon, authenticated;
revoke all on function public.cancel_emodul_upgrade_intent(bigint) from public, anon, authenticated;

grant execute on function public.save_emodul_upgrade_intent(bigint, text, text) to service_role;
grant execute on function public.get_emodul_upgrade_intent(bigint) to service_role;
grant execute on function public.resume_emodul_upgrade_intent(bigint) to service_role;
grant execute on function public.cancel_emodul_upgrade_intent(bigint) to service_role;
